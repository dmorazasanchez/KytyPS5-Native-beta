#!/bin/sh
# Regenerates upscalerShaders.h (gfx1013, wave64) from pack.s / unpack.s with llvm-mc.
set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
out=upscalerShaders.h
{ echo "// Generated by gen.sh from pack.s, unpack.s, pack_rg16f.s (llvm-mc, gfx1013, wave64). Do not edit."; echo "#pragma once"; echo "#include <cstdint>"; } > $out
for s in pack unpack pack_rg16f unpack_rgb0 copy4 copy2 copy1 copy4_a0 fg_guides scale4_a0; do
  llvm-mc -triple=amdgcn -mcpu=gfx1013 -mattr=+wavefrontsize64 -filetype=obj $s.s -o $tmp/$s.o
  llvm-objcopy -O binary --only-section=.text $tmp/$s.o $tmp/$s.bin
  echo "inline constexpr uint32_t k_upscaler_${s}[] = {" >> $out
  od -An -v -tx4 $tmp/$s.bin | tr -s ' ' '\n' | sed '/^$/d;s/^/0x/;s/$/u,/' | paste -sd' ' | fold -w 100 -s | sed 's/^/\t/' >> $out
  echo "};" >> $out
done
rm -rf $tmp
